// Regenerate tokens.css and tokens.json from mc_css.ts (the source of truth).
// Usage: node tokens.mjs
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const here = path.dirname(fileURLToPath(import.meta.url));
const src = fs.readFileSync(path.join(here, 'mc_css.ts'), 'utf8');

// Pull the custom properties out of one rule, e.g. ".mc{" or ".mc.dark{".
function vars(selector) {
  const start = src.indexOf(`\n${selector}{`);
  if (start < 0) throw new Error(`rule not found: ${selector}`);
  const body = src.slice(src.indexOf('{', start) + 1, src.indexOf('}', start));
  // Split declarations on ";" outside parentheses and quotes, keep the custom properties.
  const decls = [];
  let cur = '', depth = 0, q = '';
  for (const ch of body) {
    if (q) { if (ch === q) q = ''; cur += ch; continue; }
    if (ch === '"' || ch === "'") q = ch;
    if (ch === '(') depth++;
    if (ch === ')') depth--;
    if (ch === ';' && depth === 0) { decls.push(cur); cur = ''; continue; }
    cur += ch;
  }
  decls.push(cur);
  return decls.map((d) => d.trim()).filter((d) => d.startsWith('--')).map((d) => [d.slice(0, d.indexOf(':')), d.slice(d.indexOf(':') + 1).trim()]);
}

const base = vars('.mc');
const plex = vars('.mc.plex');
const dark = vars('.mc.dark');

const block = (sel, comment, list) => `/* ${comment} */\n${sel} {\n${list.map(([k, v]) => `  ${k}: ${v};`).join('\n')}\n}\n`;
const css = `/* Memory Cards design tokens (generated from mc_css.ts by tokens.mjs; edit there, then run node tokens.mjs). */\n\n`
  + block('.mc', 'Light, default font pair: Nunito display + Inter UI', base) + '\n'
  + block('.mc.plex', 'Font switch: IBM Plex Sans for both', plex) + '\n'
  + block('.mc.dark', 'Dark mode overrides', dark);
fs.writeFileSync(path.join(here, 'tokens.css'), css);

const pick = (re) => Object.fromEntries(base.filter(([k]) => re.test(k)));
const SPACE = ['coral', 'cyan', 'gold', 'blue', 'vio', 'green', 'orange', 'pink'];
const json = {
  $source: 'mc_css.ts (generated by tokens.mjs)',
  font: {
    display: base.find(([k]) => k === '--fd')[1],
    ui: base.find(([k]) => k === '--fu')[1],
    plexSwitch: Object.fromEntries(plex),
  },
  type: pick(/^--t-/),
  space: pick(/^--s\d$/),
  radius: pick(/^--r-/),
  size: pick(/^--(hit|ctl|label-h)$/),
  color: Object.fromEntries(base.filter(([k]) => /^--(ink|mut|faint|line|bg|paper|well|notep|pri|pri-ink|ring|ok|warn|err|err-bg|toast|agent|agent-bg|on-c)$/.test(k))),
  spaceColor: Object.fromEntries(base.filter(([k]) => SPACE.includes(k.slice(2)))),
  tint: pick(/^--tint$/),
  depth: pick(/^--(bevel|shade|sh\d)$/),
  motion: pick(/^--(m-|ease)/),
  dark: Object.fromEntries(dark),
};
fs.writeFileSync(path.join(here, 'tokens.json'), JSON.stringify(json, null, 2) + '\n');
console.log(`tokens: ${base.length} base, ${plex.length} plex, ${dark.length} dark`);
